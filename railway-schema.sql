-- PocketTrading initial MySQL schema for Railway.
-- Run once against the intended empty/new database. Do not run over production data without backup.
CREATE TABLE IF NOT EXISTS custom_users (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 email VARCHAR(190) NOT NULL UNIQUE,
 full_name VARCHAR(100) NOT NULL,
 password_hash VARCHAR(255) NOT NULL,
 balance DECIMAL(18,2) NOT NULL DEFAULT 0.00,
 kyc_status VARCHAR(30) NOT NULL DEFAULT 'pending',
 is_admin TINYINT(1) NOT NULL DEFAULT 0,
 reset_token_hash VARCHAR(255) NULL,
 reset_expires DATETIME NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NULL DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS trades (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL,
 symbol VARCHAR(20) NOT NULL,
 type VARCHAR(10) NOT NULL,
 amount DECIMAL(18,2) NOT NULL,
 leverage DECIMAL(10,2) NOT NULL DEFAULT 1,
 entry_price DECIMAL(24,10) NOT NULL,
 fee DECIMAL(18,2) NOT NULL DEFAULT 0,
 status VARCHAR(20) NOT NULL DEFAULT 'open',
 duration INT NOT NULL,
 payout_percent DECIMAL(7,2) NOT NULL,
 expected_payout DECIMAL(18,2) NOT NULL,
 result VARCHAR(30) NULL,
 pnl DECIMAL(18,2) NULL,
 profit_percent DECIMAL(7,2) NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 closed_at DATETIME NULL,
 INDEX idx_trades_user_created (user_id,created_at),
 CONSTRAINT fk_trades_user FOREIGN KEY (user_id) REFERENCES custom_users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS transactions (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL,
 amount DECIMAL(18,2) NOT NULL,
 type VARCHAR(40) NOT NULL,
 description VARCHAR(500) NOT NULL DEFAULT '',
 date DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_transactions_user_date (user_id,date),
 CONSTRAINT fk_transactions_user FOREIGN KEY (user_id) REFERENCES custom_users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS user_activities (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL,
 type VARCHAR(60) NOT NULL,
 title VARCHAR(200) NOT NULL,
 description TEXT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_activities_user_date (user_id,created_at),
 CONSTRAINT fk_activities_user FOREIGN KEY (user_id) REFERENCES custom_users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS deposit_requests (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL,
 amount DECIMAL(18,2) NOT NULL,
 currency VARCHAR(20) NOT NULL DEFAULT 'USDT',
 transaction_hash VARCHAR(255) NULL,
 screenshot MEDIUMTEXT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'pending',
 date DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_deposits_status_date (status,date),
 CONSTRAINT fk_deposits_user FOREIGN KEY (user_id) REFERENCES custom_users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS withdrawal_requests (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL,
 amount DECIMAL(18,2) NOT NULL,
 fee DECIMAL(18,2) NOT NULL DEFAULT 0,
 currency VARCHAR(20) NOT NULL DEFAULT 'USDT',
 wallet_address VARCHAR(255) NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'pending',
 date DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_withdrawals_status_date (status,date),
 CONSTRAINT fk_withdrawals_user FOREIGN KEY (user_id) REFERENCES custom_users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS kyc_requests (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL,
 full_name VARCHAR(150) NULL,
 document_type VARCHAR(50) NULL,
 document_number VARCHAR(100) NULL,
 document_front MEDIUMTEXT NULL,
 document_back MEDIUMTEXT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'pending',
 notes TEXT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_kyc_status_date (status,created_at),
 CONSTRAINT fk_kyc_user FOREIGN KEY (user_id) REFERENCES custom_users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS market_prices (
 symbol VARCHAR(20) NOT NULL PRIMARY KEY,
 name VARCHAR(100) NULL,
 price DECIMAL(24,10) NOT NULL DEFAULT 0,
 change_percent DECIMAL(12,6) NOT NULL DEFAULT 0,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS watchlist (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL,
 symbol VARCHAR(20) NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY uniq_watchlist_user_symbol (user_id,symbol),
 CONSTRAINT fk_watchlist_user FOREIGN KEY (user_id) REFERENCES custom_users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS platform_settings (
 setting_key VARCHAR(100) NOT NULL PRIMARY KEY,
 setting_value JSON NOT NULL,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
